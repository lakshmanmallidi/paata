"""Paata logo: a chukkala muggu (the dot-and-line floor drawing of Telugu homes) with the
name in English (the owner did not want Telugu lettering in it). Writes assets/logo.svg (README banner), assets/logo-mark.svg (square
mark) and firmware/src/boot_logo.h (128 x 160 boot screen, RGB565).

Run: uv run --with uharfbuzz --with fonttools --with resvg-py --with pillow .claude/tools/logo.py

The lettering is drawn as outlines from Noto Sans Telugu (its Latin letters; SIL Open Font
License), fetched from the Google Fonts repository on first run and kept outside the repo.
"""
import io, math, pathlib, urllib.request
import uharfbuzz as hb, resvg_py
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
CACHE = pathlib.Path.home() / ".cache" / "paata-logo-fonts"
FONTS = {
    "latin": ("NotoSansTelugu.ttf", "https://github.com/google/fonts/raw/main/ofl/notosanstelugu/NotoSansTelugu%5Bwdth%2Cwght%5D.ttf"),
}
BLACK, ORANGE, GREY, WHITE = "#0B0B0D", "#F08A3C", "#8C8E96", "#FFFFFF"


def font_path(key):
    name, url = FONTS[key]
    CACHE.mkdir(parents=True, exist_ok=True)
    p = CACHE / name
    if not p.exists(): urllib.request.urlretrieve(url, p)
    return str(p)


def text(key, s, cx, cy, h, fill, wght=None, spacing=0.0):
    """Text as one outline path, centred on (cx, cy) and h tall. spacing is extra advance in em."""
    face = hb.Face(hb.Blob.from_file_path(font_path(key))); font = hb.Font(face)
    if wght: font.set_variations({"wght": wght})
    buf = hb.Buffer(); buf.add_str(s); buf.guess_segment_properties(); hb.shape(font, buf)
    d, x, xs, ys = [], 0, [], []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        rec = RecordingPen(); font.draw_glyph_with_pen(info.codepoint, rec)
        pen = SVGPathPen(None)
        for op, args in rec.value:
            pts = [(px + x + pos.x_offset, py + pos.y_offset) for px, py in args]
            xs += [p[0] for p in pts]; ys += [p[1] for p in pts]
            getattr(pen, op)(*pts)
        d.append(pen.getCommands()); x += pos.x_advance + spacing * face.upem
    k = h / (max(ys) - min(ys))
    tx, ty = cx - k * (min(xs) + max(xs)) / 2, cy + k * (min(ys) + max(ys)) / 2
    return f'<path transform="translate({tx:.2f},{ty:.2f}) scale({k:.5f},{-k:.5f})" d="{" ".join(d)}" fill="{fill}"/>'


def muggu(cx, cy, s):
    """Four-petal muggu: one unbroken line round a grid of dots. s is the outer radius."""
    pts = []
    for i in range(361):
        t = math.radians(i); r = s * (0.62 + 0.36 * math.cos(4 * t))
        pts.append(f"{cx + r * math.cos(t):.2f},{cy + r * math.sin(t):.2f}")
    out = [f'<path d="M{" L".join(pts)}Z" fill="none" stroke="{ORANGE}" stroke-width="{0.085 * s:.2f}" stroke-linejoin="round"/>']
    for i in range(4):
        for r, t in ((0.68, i * 90), (0.75, i * 90 + 45)):
            out.append(f'<circle cx="{cx + r * s * math.cos(math.radians(t)):.2f}" cy="{cy + r * s * math.sin(math.radians(t)):.2f}" r="{0.065 * s:.2f}" fill="{GREY}"/>')
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{0.11 * s:.2f}" fill="{WHITE}"/>')
    return "".join(out)


def svg(w, h, body, radius=0):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}">'
            f'<rect width="{w}" height="{h}" rx="{radius}" fill="{BLACK}"/>{body}</svg>')


banner = svg(720, 260, muggu(140, 130, 92) + text("latin", "paata", 440, 130, 92, WHITE, wght=700, spacing=0.02), radius=28)
mark = svg(256, 256, muggu(128, 128, 100), radius=48)
boot = svg(128, 160, muggu(64, 60, 40) + text("latin", "paata", 64, 128, 22, WHITE, wght=700, spacing=0.02))

(ROOT / "assets").mkdir(exist_ok=True)
(ROOT / "assets" / "logo.svg").write_text(banner)
(ROOT / "assets" / "logo-mark.svg").write_text(mark)

img = Image.open(io.BytesIO(bytes(resvg_py.svg_to_bytes(svg_string=boot, width=128, height=160)))).convert("RGB")
px = [((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3) for r, g, b in img.get_flattened_data()]
rows = [", ".join(f"0x{v:04X}" for v in px[i:i + 16]) for i in range(0, len(px), 16)]
(ROOT / "firmware" / "src" / "boot_logo.h").write_text(
    "// Boot screen, 128 x 160, RGB565. Generated by .claude/tools/logo.py; do not edit.\n"
    "#pragma once\n#include <stdint.h>\n\nconst uint16_t BOOT_LOGO[128 * 160] = {\n  " + ",\n  ".join(rows) + "\n};\n")
img.save(pathlib.Path(__file__).with_name("_boot_preview.png"))
print("wrote assets/logo.svg, assets/logo-mark.svg, firmware/src/boot_logo.h")
